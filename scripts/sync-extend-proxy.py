#!/usr/bin/env python3
"""Keep plugins/multicloud-extend/.../assets/extend-proxy.yaml in step with the platform manifest.

AUTHORING HOME: tools/extend-proxy/deploy/extend-proxy.yaml in Multicloud's private platform repo.
Edit it there, then run this script here and commit the result. Never edit the asset by hand:
the next sync silently overwrites it, and --check fails until the asset matches the source.

The asset is the customer copy: the same manifest with the internal comments removed, the two
fill-in values left as placeholders (<pool>, <peering-id>), the route moved to my-apps, and the
image pinned to the release in assets/extend-proxy.source.json.

Usage:
  scripts/sync-extend-proxy.py                  # write the asset and its source record
  scripts/sync-extend-proxy.py --check          # write nothing; exit 1 on any drift
  scripts/sync-extend-proxy.py --from ../platform --tag 0.1.3
Source resolution: --from, then $MULTICLOUD_PLATFORM_REPO, then ../platform.
Exit: 0 in sync (or written), 1 drift or unknown platform change, 2 usage or missing source.
"""
import argparse
import hashlib
import json
import os
import re
import subprocess
import sys

SRC_REL = "tools/extend-proxy/deploy/extend-proxy.yaml"
SKILL_DIR = "plugins/multicloud-extend/skills/multicloud-extend"
ASSET = f"{SKILL_DIR}/assets/extend-proxy.yaml"
RECORD = f"{SKILL_DIR}/assets/extend-proxy.source.json"
ROUTE_NS = "my-apps"

HEADER = """\
# Extend proxy: lets pods and Services in your cluster reach the pods that run on your Multicloud pool.
# The agent fills in the two placeholders <pool> and <peering-id> (see the proxy-manifest step).
# Nothing else needs to change. The API key is a separate Secret, made in the proxy-secret step.
#
# The namespace multicloud-extend-proxy is never labelled for Liqo offloading.
# GENERATED by scripts/sync-extend-proxy.py from the Multicloud platform manifest. Do not edit.
"""

# Each substitution must match exactly the expected number of times. If the platform
# manifest renames or moves one of these, the sync stops and names it, so the rule can be
# updated on purpose instead of drifting silently.
SUBSTITUTIONS = [
    (r"multicloud/extend-proxy:<tag>", "multicloud/extend-proxy:{tag}", 1),
    (r"^(\s*)pool: <pool name>$", r"\1pool: <pool>", 1),
    (r"^(\s*)peering_id: <peering id>$", r"\1peering_id: <peering-id>", 1),
    (r"\{listen_port: 8000, namespace: demo, service: vllm, port: 8000\}",
     "{listen_port: 8000, namespace: " + ROUTE_NS + ", service: vllm, port: 8000}", 1),
    (r"namespace: demo\s*$", "namespace: " + ROUTE_NS, 2),
]
ALLOWED_PLACEHOLDERS = {"<pool>", "<peering-id>"}


def fail_unknown(msg):
    print(f"UNKNOWN  {msg}", file=sys.stderr)
    print("         The platform manifest changed in a way this sync does not handle yet.", file=sys.stderr)
    print("         Update SUBSTITUTIONS in scripts/sync-extend-proxy.py, then run it again.", file=sys.stderr)
    sys.exit(1)


def transform(src_text, tag):
    lines = src_text.replace("\r\n", "\n").split("\n")
    body_lines = [ln for ln in lines if ln.strip() and not ln.strip().startswith("#")]
    body = "\n".join(body_lines) + "\n"
    for pattern, repl, expected in SUBSTITUTIONS:
        repl = repl.replace("{tag}", tag)
        body, n = re.subn(pattern, repl, body, flags=re.MULTILINE)
        if n != expected:
            fail_unknown(f"expected {expected} match(es) for {pattern!r}, found {n}")
    if "demo" in body:
        fail_unknown("the word 'demo' is still in the manifest after the route change")
    left = {m for m in re.findall(r"<[^>\s]+>", body)} - ALLOWED_PLACEHOLDERS
    if left:
        fail_unknown(f"unexpected placeholder(s) in the manifest: {sorted(left)}")
    return HEADER + body


def platform_commit(repo):
    try:
        out = subprocess.run(["git", "-C", repo, "rev-parse", "--short", "HEAD"],
                             capture_output=True, text=True, check=True)
        return out.stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return None


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--from", dest="src_repo", help="path to the platform repo checkout")
    ap.add_argument("--tag", help="image tag to pin (default: the tag in the source record)")
    ap.add_argument("--check", action="store_true", help="compare only; write nothing")
    args = ap.parse_args()

    root = subprocess.run(["git", "rev-parse", "--show-toplevel"], capture_output=True,
                          text=True, check=True).stdout.strip()
    repo = args.src_repo or os.environ.get("MULTICLOUD_PLATFORM_REPO") or os.path.join(root, "..", "platform")
    src_path = os.path.join(repo, SRC_REL)
    if not os.path.isfile(src_path):
        print(f"MISSING  {src_path}\n         pass --from <platform repo> or set MULTICLOUD_PLATFORM_REPO", file=sys.stderr)
        sys.exit(2)

    asset_path = os.path.join(root, ASSET)
    record_path = os.path.join(root, RECORD)
    record = {}
    if os.path.isfile(record_path):
        with open(record_path, encoding="utf-8") as f:
            record = json.load(f)
    tag = args.tag or record.get("image_tag")
    if not tag:
        print("MISSING  no image tag: pass --tag <release>", file=sys.stderr)
        sys.exit(2)

    with open(src_path, "rb") as f:
        raw = f.read()
    src_text = raw.decode("utf-8")
    generated = transform(src_text, tag)
    new_record = {
        "source": SRC_REL,
        "source_sha256": hashlib.sha256(raw).hexdigest(),
        "platform_commit": platform_commit(repo),
        "image_tag": tag,
    }

    asset_now = None
    if os.path.isfile(asset_path):
        with open(asset_path, encoding="utf-8") as f:  # universal newlines: CRLF on disk is not drift
            asset_now = f.read()
    asset_ok = asset_now == generated
    record_ok = record == new_record

    if args.check:
        if asset_ok and record_ok:
            print(f"OK       {ASSET} matches {SRC_REL} (platform commit {new_record['platform_commit']}, image {tag})")
            return
        if not asset_ok:
            print(f"DRIFT    {ASSET} does not match the platform manifest")
        if not record_ok:
            print(f"DRIFT    {RECORD} does not record the current platform manifest")
        print("         run: scripts/sync-extend-proxy.py   (then commit the result)")
        sys.exit(1)

    with open(asset_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(generated)
    with open(record_path, "w", encoding="utf-8", newline="\n") as f:
        json.dump(new_record, f, indent=2)
        f.write("\n")
    print(f"WROTE    {ASSET}")
    print(f"WROTE    {RECORD}  (platform commit {new_record['platform_commit']}, image {tag})")


if __name__ == "__main__":
    main()
